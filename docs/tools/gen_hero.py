#!/usr/bin/env python3
"""gen_hero.py — the ONE committed docs-media exception.

docs/_static/photos/sim_home.png is gitignored build output (the
device composite of docs/tools/composite_dark.py, regenerated by every
media run) — every docs page embeds it from disk. But the README is
GitHub-facing: it renders for readers WITHOUT a media run, so its
signature image must be committed. This script downscales the current
composite to ~1024 px and writes docs/_static/photos/sim_home.webp —
tracked, LFS (the .gitattributes *.webp rule), the documented
exception to "docs media is never committed".

Regenerate after any media run that changes the composite (the home
screen, the product photo, the fit):

    docs/.venv/bin/python docs/tools/gen_hero.py

Fresh-tree case (CI's first media run on a clean clone): the composite
does not exist yet — the figs sweep the media builder runs FIRST
predates the uisim + composite steps that produce it. That is not an
error: the committed LFS webp (pulled by the checkout) is what ships,
and a by-hand run after the media run refreshes it.
"""

import sys
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
PHOTOS = HERE.parent / "_static" / "photos"
SRC = PHOTOS / "sim_home.png"
DST = PHOTOS / "sim_home.webp"
TARGET = 1024  # the long edge, px (the README's display size with headroom)


def main():
    if not SRC.exists():
        print(f"gen_hero.py: {SRC} missing (fresh tree) — keeping the "
              f"committed {DST.name}")
        return
    img = Image.open(SRC).convert("RGB")
    w, h = img.size
    scale = TARGET / max(w, h)
    if scale < 1.0:
        img = img.resize((max(1, round(w * scale)), max(1, round(h * scale))),
                         Image.LANCZOS)
    img.save(DST, "WEBP", quality=88)
    print(f"wrote {DST} ({img.size[0]}x{img.size[1]}, "
          f"{DST.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
