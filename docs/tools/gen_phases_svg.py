#!/usr/bin/env python3
"""Draw the school-level moon-phase diagram (docs/how-it-works.rst).

Top half: the Sun-Earth-Moon system seen from above the North Pole. The
Sun's light comes from the left, so every Moon is lit on its left half.
Bottom row: what an observer in the northern hemisphere sees at each of
the eight positions.

Writes docs/_graphs/moon-phases.svg (committed; re-run after editing):
    python3 docs/tools/gen_phases_svg.py
"""
from __future__ import annotations

import math
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "_graphs" / "moon-phases.svg"

W, H = 900, 640
EX, EY, ORBIT = 470, 230, 150          # Earth centre, orbit radius
R_TOP, R_ROW = 20, 30                  # Moon radii (top view, bottom row)
LIT, DARK, LINE, TEXT = "#f3f1e7", "#3b3b3b", "#8a8a8a", "#444"

# (name, age as a fraction of the synodic month)
PHASES = [
    ("New moon", 0.0), ("Waxing crescent", 0.125),
    ("First quarter", 0.25), ("Waxing gibbous", 0.375),
    ("Full moon", 0.5), ("Waning gibbous", 0.625),
    ("Last quarter", 0.75), ("Waning crescent", 0.875),
]


def seen_from_earth(cx: float, cy: float, r: float, age: float) -> str:
    """Disk as seen from the northern hemisphere: dark base + lit shape."""
    out = [f'<circle cx="{cx:.1f}" cy="{cy:.1f}" r="{r}" fill="{DARK}" '
           f'stroke="{LINE}" stroke-width="1.2"/>']
    if age == 0.0:
        return "".join(out)
    if age == 0.5:
        out.append(f'<circle cx="{cx:.1f}" cy="{cy:.1f}" r="{r}" fill="{LIT}"/>')
        return "".join(out)
    e = 2 * math.pi * age
    rx = abs(math.cos(e)) * r
    crescent = math.cos(e) > 0
    top, bot = f"{cx:.1f},{cy - r:.1f}", f"{cx:.1f},{cy + r:.1f}"
    if age < 0.5:      # waxing: lit limb on the right
        limb, back = 1, (0 if crescent else 1)
    else:              # waning: lit limb on the left
        limb, back = 0, (1 if crescent else 0)
    out.append(f'<path d="M {top} A {r} {r} 0 0 {limb} {bot} '
               f'A {rx:.2f} {r} 0 0 {back} {top} Z" fill="{LIT}"/>')
    return "".join(out)


def top_view_moon(cx: float, cy: float, r: float) -> str:
    """Moon seen from above: the half facing the Sun (left) is lit."""
    return (f'<circle cx="{cx:.1f}" cy="{cy:.1f}" r="{r}" fill="{DARK}" '
            f'stroke="{LINE}" stroke-width="1.2"/>'
            f'<path d="M {cx:.1f},{cy - r:.1f} A {r} {r} 0 0 0 '
            f'{cx:.1f},{cy + r:.1f} Z" fill="{LIT}"/>')


def main() -> None:
    p = [f'<?xml version="1.0" encoding="UTF-8"?>\n'
         f'<!-- Generated by docs/tools/gen_phases_svg.py — edit the script, '
         f'not this file. -->\n'
         f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" '
         f'role="img" aria-label="Moon phases: the Moon orbiting the Earth '
         f'with sunlight from the left, and the eight phases as seen from '
         f'the northern hemisphere.">',
         f'<rect x="0" y="0" width="{W}" height="{H}" rx="14" fill="#fafaf8"/>',
         f'<g font-family="sans-serif" font-size="15" fill="{TEXT}">',
         '<defs><marker id="ray" viewBox="0 0 10 10" refX="9" refY="5" '
         'markerWidth="6" markerHeight="6" orient="auto">'
         '<path d="M0 0 L10 5 L0 10 z" fill="#e0a21a"/></marker></defs>']
    # the Sun and its light
    p.append('<circle cx="-40" cy="230" r="95" fill="#f2b632"/>')
    p.append('<text x="20" y="360" font-size="16">Sun</text>')
    for y in (110, 170, 230, 290, 350):
        p.append(f'<line x1="80" y1="{y}" x2="190" y2="{y}" stroke="#e0a21a" '
                 f'stroke-width="2" marker-end="url(#ray)"/>')
    p.append('<text x="80" y="400" font-size="13">sunlight</text>')
    # orbit and Earth
    p.append(f'<circle cx="{EX}" cy="{EY}" r="{ORBIT}" fill="none" '
             f'stroke="{LINE}" stroke-width="1.2" stroke-dasharray="5 5"/>')
    p.append(f'<circle cx="{EX}" cy="{EY}" r="26" fill="#3d7ab8"/>')
    p.append(f'<path d="M {EX},{EY - 26} A 26 26 0 0 1 {EX},{EY + 26} Z" '
             f'fill="#1f3f60"/>')
    p.append(f'<text x="{EX}" y="{EY + 5}" text-anchor="middle" '
             f'fill="#fff" font-size="13">Earth</text>')
    # the Moon at its eight positions (counter-clockwise seen from north)
    for i, (name, age) in enumerate(PHASES):
        ang = math.pi + 2 * math.pi * age          # new moon = toward the Sun
        mx = EX + ORBIT * math.cos(ang)
        my = EY - ORBIT * math.sin(ang)
        p.append(top_view_moon(mx, my, R_TOP))
        p.append(f'<text x="{mx:.1f}" y="{my + 5:.1f}" text-anchor="middle" '
                 f'font-size="12" fill="#a63b2a" font-weight="bold" '
                 f'dx="{36 * math.cos(ang):.1f}" dy="{-36 * math.sin(ang):.1f}">'
                 f'{i + 1}</text>')
    p.append(f'<text x="{EX + ORBIT + 90}" y="80" font-size="13">'
             f'seen from above</text>')
    p.append(f'<text x="{EX + ORBIT + 90}" y="98" font-size="13">'
             f'the North Pole</text>')
    # the bottom row: what we see from Earth
    y0 = 500
    p.append(f'<text x="{W / 2}" y="{y0 - 58}" text-anchor="middle" '
             f'font-size="16">What you see from Earth (northern hemisphere)</text>')
    step = (W - 80) / len(PHASES)
    for i, (name, age) in enumerate(PHASES):
        cx = 40 + step * (i + 0.5)
        p.append(seen_from_earth(cx, y0, R_ROW, age))
        p.append(f'<text x="{cx:.1f}" y="{y0 + 52}" text-anchor="middle" '
                 f'font-size="12" fill="#a63b2a" font-weight="bold">{i + 1}</text>')
        for j, word in enumerate(name.split(" ")):
            p.append(f'<text x="{cx:.1f}" y="{y0 + 70 + 15 * j}" '
                     f'text-anchor="middle" font-size="12">{word}</text>')
    p.append("</g></svg>\n")
    OUT.write_text("\n".join(p))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
